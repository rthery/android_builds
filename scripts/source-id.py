#!/usr/bin/env python3
"""Print the source id of a tree: the same for every build of the same sources.

The id hashes the sorted "<path> <revision>" lines of a resolved manifest
(`repo manifest -r`, or a device's pinned manifest.xml). Projects that
changes.json lists without a repository are generated by the recipe from
pinned inputs (extracted vendor blobs), so they are left out. With --tree,
uncommitted tracked changes in a fork or the device tree add "-dirty".
"""
import argparse,hashlib,json,pathlib,re,subprocess,sys
import xml.etree.ElementTree as ET

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('manifest',type=pathlib.Path,help='resolved manifest XML')
p.add_argument('--changes',type=pathlib.Path,required=True,help='devices/<device>/changes.json')
p.add_argument('--tree',type=pathlib.Path,help='synced source tree to check for uncommitted changes')
p.add_argument('--device-path',default='device/lge/bullhead',help='device tree path inside the source tree')
a=p.parse_args()

changes=json.loads(a.changes.read_text())
generated={e['path'] for e in changes if 'repository' not in e}
lines=[]
for project in ET.parse(a.manifest).getroot().iter('project'):
 path=project.get('path') or project.get('name')
 if path in generated:continue
 revision=project.get('revision') or ''
 if not re.fullmatch(r'[0-9a-f]{40}',revision):sys.exit(f'{path}: revision {revision!r} is not a commit; use a resolved manifest')
 lines.append(f'{path} {revision}\n')
source_id=hashlib.sha256(''.join(sorted(lines)).encode()).hexdigest()[:16]

if a.tree:
 forks=[e['path'] for e in changes if 'repository' in e]+[a.device_path]
 for path in dict.fromkeys(forks):
  status=subprocess.run(['git','-C',str(a.tree/path),'status','--porcelain','--untracked-files=no'],check=True,capture_output=True,text=True).stdout
  if status.strip():
   source_id+='-dirty'
   break
print(source_id)
