#!/usr/bin/env python3
"""Check that a synced tree is exactly the published recipe.

Projects pinned in the device manifest must sit at the pinned commit. Every
other project's HEAD must be reachable from what `repo sync` fetched for the
upstream manifest branch (refs/remotes/m/<branch>), so it carries no local
commits; the resolved manifest records the exact revision. No project may have
tracked or untracked changes, except an overlay: a file the runner mounts over
the tree, accepted only when it is byte-identical to the recipe's copy.
Generated paths are skipped.
"""
import argparse,concurrent.futures,pathlib,subprocess,sys
import xml.etree.ElementTree as ET

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('resolved',type=pathlib.Path,help='repo manifest -r output')
p.add_argument('recipe',type=pathlib.Path,help='device manifest with the pins')
p.add_argument('--tree',type=pathlib.Path,required=True)
p.add_argument('--branch',required=True,help='upstream manifest branch')
p.add_argument('--generated',action='append',default=[],help='path regenerated by the recipe')
p.add_argument('--overlay',action='append',default=[],help='TREE_PATH=RECIPE_FILE mounted over the tree by the runner')
a=p.parse_args()

def git(path,*args):
 return subprocess.run(['git','--no-optional-locks','-C',str(a.tree/path),*args],capture_output=True,text=True)

def projects(manifest):
 return {e.get('path') or e.get('name'):e for e in ET.parse(manifest).getroot().iter('project')}
overlays={}
for spec in a.overlay:
 target,source=spec.split('=',1)
 overlays[target]=pathlib.Path(source).read_bytes()
recipe,tree=projects(a.recipe),projects(a.resolved)
pins={path:e.get('revision') for path,e in recipe.items()}
resolved={path:e.get('revision') for path,e in tree.items()}
problems=[f'{path}: pinned but not in the tree' for path in pins if path not in resolved and path not in a.generated]
# resolved.xml is published as the source list, so it must name the repositories the pins come from.
problems+=[f'{path}: tree manifest names {tree[path].get("name")}, recipe {e.get("name")}'
 for path,e in recipe.items() if path in tree and tree[path].get('name')!=e.get('name')]

def overlaid(path,line):
 target=f'{path}/{line[3:]}'
 return line[:3]==' M ' and target in overlays and (a.tree/target).read_bytes()==overlays[target]

def check(item):
 path,head=item
 if path in a.generated:return []
 found=[]
 if path in pins:
  if head!=pins[path]:found.append(f'{path}: HEAD {head} is not the pin {pins[path]}')
 else:
  if git(path,'merge-base','--is-ancestor',head,f'refs/remotes/m/{a.branch}').returncode:
   found.append(f'{path}: HEAD {head} is not on m/{a.branch}')
 status=git(path,'status','--porcelain')
 if status.returncode:found.append(f'{path}: git status failed: {status.stderr.strip()}')
 changed=[line for line in status.stdout.splitlines() if not line.rstrip('/').endswith('__pycache__')
  and not overlaid(path,line)]
 found+=[f'{path}: {line}' for line in changed[:5]]
 if len(changed)>5:found.append(f'{path}: {len(changed)-5} more changes')
 return found

with concurrent.futures.ThreadPoolExecutor(8) as pool:
 for found in pool.map(check,sorted(resolved.items())):problems+=found
manifest=subprocess.run(['git','-C',str(a.tree/'.repo/manifests'),'merge-base','--is-ancestor','HEAD',f'origin/{a.branch}'])
if manifest.returncode:problems.append(f'.repo/manifests: HEAD is not on origin/{a.branch}')
for line in problems:print(line)
if problems:sys.exit(f'{len(problems)} problem(s): the tree is not the published recipe')
print(f'{len(resolved)} projects match: {len(pins)} pinned, the rest on m/{a.branch}, all clean')
